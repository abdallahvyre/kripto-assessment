class WAFModule:
    def __init__(self, target: str, console, active: bool = False):
        self.target = target
        self.console = console
        self.active = active
        self.session = RateLimitedSession()


    def run(self) -> dict:
        results = {"detected": False, "waf_name": None, "evidence": "", "details": [], "error": None}

        info(self.console, "Detecting WAF/CDN...")

        
        try:
            resp_normal = self.session.get(self.target, timeout=TIMEOUT)
        except Exception as e:
            from core.banner import error
            results["error"] = str(e)
            error(self.console, f"Failed to connect: {e}")
            warning(self.console, "WAF detection INCONCLUSIVE - target was unreachable.")
            return results

        responses = [resp_normal]
        if self.active:
            
            attack_payloads = [
                f"{self.target}/?id=1%27%20AND%20%271%27=%272",
                f"{self.target}/?q=%3Ckripto-probe%3E",
                f"{self.target}/?file=..%2F..%2Fkripto-probe",
            ]
            for payload_url in attack_payloads:
                try:
                    resp = self.session.get(payload_url, timeout=TIMEOUT)
                    responses.append(resp)
                except Exception:
                    pass

        
        for resp in responses:
            headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
            cookies_str = " ".join(f"{c.name}={c.value}" for c in resp.cookies).lower()
            body_lower = resp.text[:5000].lower()
            all_text = " ".join(headers_lower.values()) + " " + cookies_str + " " + body_lower

            for waf_name, sigs in WAF_SIGNATURES.items():
                evidence_parts = []

                for h in sigs["headers"]:
                    if h.lower() in headers_lower:
                        evidence_parts.append(f"Header: {h}={headers_lower[h.lower()]}")

                for c in sigs["cookies"]:
                    if c.lower() in cookies_str:
                        evidence_parts.append(f"Cookie: {c}")

                for b in sigs["body"]:
                    if b.lower() in body_lower:
                        evidence_parts.append(f"Body: '{b}'")

                if evidence_parts:
                    results["detected"] = True
                    results["waf_name"] = waf_name
                    results["evidence"] = "; ".join(evidence_parts)
                    results["details"].append({
                        "waf": waf_name,
                        "evidence": evidence_parts,
                    })

        
        if self.active and not results["detected"]:
            for resp in responses[1:]:
                if resp.status_code in (403, 406, 429, 503):
                    if resp.status_code != resp_normal.status_code:
                        results["detected"] = True
                        results["waf_name"] = "Unknown WAF"
                        results["evidence"] = f"Attack payload returned {resp.status_code} (normal: {resp_normal.status_code})"
                        break

        if results["detected"]:
            vuln(self.console, f"WAF Detected: [bold]{results['waf_name']}[/bold]")
            found(self.console, f"Evidence: {results['evidence'][:100]}")
        else:
            success(self.console, "No WAF signature detected in responses")

        return results
